import { readFile, writeFile, mkdir } from "node:fs/promises";

const base = new URL("../supabase/functions/blog-mcp/", import.meta.url);
const { dependencies } = JSON.parse(await readFile(new URL("package.json", base), "utf8"));
let source = await readFile(new URL("server.ts", base), "utf8");
source = source.replace(/^import .* from '\.\/images\.ts';\r?\n/m, "");
let imageSource = await readFile(new URL("images.ts", base), "utf8");
imageSource = imageSource.replace(/^import .*;\r?\n/gm, "").replace(/^export /gm, "");
source += "\n" + imageSource;
source = "import { createClient } from '@supabase/supabase-js';\n" + source;
for (const [name, version] of Object.entries(dependencies)) {
  source = source.replaceAll(`from '${name}'`, `from 'npm:${name}@${version}'`);
}
const entry = await readFile(new URL("index.ts", base), "utf8");
source += "\n" + entry.slice(entry.indexOf("const url ="));
const destination = new URL("../supabase/dashboard/", import.meta.url);
await mkdir(destination, { recursive: true });
await writeFile(
  new URL("blog-mcp.ts", destination),
  "// Generated by node scripts/prepare-mcp-dashboard.mjs. Paste this entire file into index.ts.\n" +
    source,
);
console.log("Prepared supabase/dashboard/blog-mcp.ts");
